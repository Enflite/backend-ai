import type { EvalCase, EvalToolDef } from '../types.js';

// ---------------------------------------------------------------------------
// Phase 6 cases — capability-aware assistance, generalized agentic loops,
// and repo-aware coding.
//
// These are deterministic CI cases (each mockResponse passes its own
// judge — mocks never invent a verdict). They exercise:
//
// - Multi-file coding grounded in caller-supplied files: explanations cite
//   only real paths/symbols (invented-file/API penalties).
// - Unified-diff change format for requested code changes.
// - Asking for missing files instead of guessing.
// - Generalized tool chains: the agentic loop is a tool-family-agnostic
//   engine, so a non-SyteLine family (repo search/read, calc) chains
//   correctly with dependent values.
// ---------------------------------------------------------------------------

